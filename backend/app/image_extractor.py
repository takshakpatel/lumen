"""Extract and semantically interpret images, charts, and diagrams from PDFs using PyMuPDF and Groq Vision.

Each image is saved to `extracted_images/<doc_stem>/`, and a LangChain Document
is created with a deep visual transcription and analysis generated by Groq's multimodal
vision model, preserving data points, axes, trends, and conclusions.
"""

from __future__ import annotations

import base64
import hashlib
import os
from pathlib import Path
from typing import Any

from dotenv import load_dotenv

_ENV_PATH = Path(__file__).resolve().parent.parent / ".env"
load_dotenv(dotenv_path=_ENV_PATH, override=True)

import pymupdf as fitz  # PyMuPDF
from langchain_core.documents import Document


def _analyze_image_with_vision(
    image_bytes: bytes,
    filename: str,
    page_num: int,
    caption: str,
) -> str:
    """Analyze a chart, graph, diagram, or table using Groq multimodal vision."""
    api_key = os.getenv("GROQ_API_KEY")
    if not api_key:
        return ""

    try:
        from groq import Groq

        client = Groq(api_key=api_key)
        b64 = base64.b64encode(image_bytes).decode("utf-8")

        prompt = (
            f"You are an expert visual document analyst. Analyze this figure, chart, table, or visual image "
            f"extracted from document '{filename}' on page {page_num}.\n"
            f"Nearby caption: {caption or 'None'}\n\n"
            "Instructions:\n"
            "1. If this is a chart or graph: Transcribe title, axes, labels, data points, values, and trends.\n"
            "2. If this is a diagram or flowchart: Transcribe the components, connections, and workflow logic.\n"
            "3. If this contains text or a table: Transcribe all visible text, numbers, and data points accurately.\n"
            "4. State the primary insight or conclusion conveyed by this visual.\n\n"
            "Provide a concise, factual, and complete transcription."
        )

        model_name = os.getenv("VISION_MODEL", "qwen/qwen3.8-27b")
        res = client.chat.completions.create(
            model=model_name,
            messages=[
                {
                    "role": "user",
                    "content": [
                        {"type": "text", "text": prompt},
                        {
                            "type": "image_url",
                            "image_url": {"url": f"data:image/png;base64,{b64}"},
                        },
                    ],
                }
            ],
            max_tokens=450,
            temperature=0.1,
        )
        return res.choices[0].message.content.strip()
    except Exception as e:
        print(f"Warning: Vision analysis skipped for {filename} p.{page_num}: {e}")
        return ""


def extract_images_from_pdf(
    pdf_path: str | Path,
    out_dir: str | Path = "extracted_images",
    min_width: int = 80,
    min_height: int = 80,
) -> list[Document]:
    """Extract visible images/graphs from a PDF, analyze them with Groq Vision, and return Document objects."""
    pdf_path = Path(pdf_path)
    doc_stem = pdf_path.stem
    save_dir = Path(out_dir) / doc_stem
    save_dir.mkdir(parents=True, exist_ok=True)

    try:
        pdf = fitz.open(str(pdf_path))
    except Exception as e:
        print(f"Warning: Failed to open PDF for image extraction: {e}")
        return []

    image_docs: list[Document] = []
    seen_hashes: set[str] = set()

    for page_num in range(len(pdf)):
        page = pdf[page_num]
        try:
            images = page.get_images(full=True)
        except Exception:
            continue

        text_blocks = page.get_text("blocks")

        for img_index, img_info in enumerate(images):
            xref = img_info[0]
            try:
                pix = fitz.Pixmap(pdf, xref)
                # Convert non-RGB pixmaps (e.g. CMYK) to RGB
                if pix.n >= 5:
                    pix = fitz.Pixmap(fitz.csRGB, pix)
            except Exception:
                continue

            if pix.width < min_width or pix.height < min_height:
                continue

            img_bytes = pix.tobytes("png")
            img_hash = hashlib.md5(img_bytes).hexdigest()
            if img_hash in seen_hashes:
                continue
            seen_hashes.add(img_hash)

            img_filename = f"page{page_num + 1}_img{img_index + 1}.png"
            img_path = save_dir / img_filename
            try:
                img_path.write_bytes(img_bytes)
            except Exception as e:
                print(f"Warning: Failed to save image {img_filename}: {e}")

            caption = _find_caption(text_blocks, img_info, page)

            # Perform AI Multimodal Vision Analysis of chart/figure
            visual_analysis = _analyze_image_with_vision(
                image_bytes=img_bytes,
                filename=pdf_path.name,
                page_num=page_num + 1,
                caption=caption,
            )

            # Build rich semantic representation
            content_parts = [
                f"[Visual Figure / Chart — {pdf_path.name}, Page {page_num + 1} ({img_filename})]"
            ]
            if visual_analysis:
                content_parts.append(visual_analysis)
            if caption:
                content_parts.append(f"Nearby Caption: {caption}")

            page_content = "\n\n".join(content_parts).strip()

            image_docs.append(
                Document(
                    page_content=page_content,
                    metadata={
                        "source": str(pdf_path),
                        "filename": pdf_path.name,
                        "type": "image",
                        "image_path": str(img_path),
                        "page": page_num + 1,
                        "width": pix.width,
                        "height": pix.height,
                        "caption": caption,
                        "chunk_index": len(image_docs),
                        "has_visual_analysis": bool(visual_analysis),
                    },
                )
            )

    pdf.close()
    return image_docs


def _find_caption(text_blocks: list, img_info: tuple, page) -> str:
    """Find the nearest text block below an image (likely a caption)."""
    try:
        img_rect = page.get_image_rects(img_info[0])
        if not img_rect:
            return ""
        rect = img_rect[0]
    except Exception:
        return ""

    captions = []
    for block in text_blocks:
        if block[6] != 0:  # text blocks only
            continue
        x0, y0, x1, y1, text = block[0], block[1], block[2], block[3], block[4]
        text = text.strip()
        if not text or len(text) < 4:
            continue
        if (
            y0 >= rect.y1 - 10
            and y0 - rect.y1 < 70
            and x0 < rect.x1 + 30
            and x1 > rect.x0 - 30
        ):
            captions.append(text)

    return " ".join(captions[:2]) if captions else ""


def extract_all_images(
    paths: list[str | Path],
    out_dir: str | Path = "extracted_images",
) -> list[Document]:
    """Run image extraction across multiple files."""
    all_docs: list[Document] = []
    for p in paths:
        p = Path(p)
        if p.suffix.lower() == ".pdf":
            all_docs.extend(extract_images_from_pdf(p, out_dir=out_dir))
    return all_docs
